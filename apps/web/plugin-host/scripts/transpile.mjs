// Turns each plugin component (built by locora-runtime's build script, for wasm32-wasip2) into an
// ES module, and writes a shim per plugin that connects its host imports to src/host-core.mjs.
// Usage: node scripts/transpile.mjs <plugin.wasm>... (output goes to dist/<plugin id>/)
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const jco = join(root, 'node_modules', '.bin', 'jco');
const HOST_FUNCTIONS = ['log', 'subscribe', 'publish', 'provide', 'registerFilter', 'callHost', 'kvGet', 'kvSet'];

for (const wasm of process.argv.slice(2)) {
  const id = basename(wasm, '.wasm').replaceAll('_', '-');
  const out = join(root, 'dist', id);
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'host.mjs'), shim(id));
  execFileSync(jco, ['transpile', resolve(wasm), '-o', out, '--map', 'locora:plugin/host=./host.mjs', '--no-typescript'], { stdio: 'inherit' });
  console.log(`transpiled ${id} -> dist/${id}/`);
}

function shim(id) {
  return `// Generated by scripts/transpile.mjs: the host functions of plugin "${id}".
import { hostFor } from '${'../../src/host-core.mjs'}';
const bound = hostFor(${JSON.stringify(id)});
export const { ${HOST_FUNCTIONS.join(', ')} } = bound;
`;
}

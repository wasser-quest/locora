"""Adds the release signing to the generated Android project (src-tauri/gen/android), once.

The project is generated by `cargo tauri android init` and not versioned, so the build script
applies this on every release build. The key's properties file is named by the environment
variable LOCORA_ANDROID_KEYSTORE at build time; without it the release stays unsigned.
"""
import sys

MARK = "// locora: release signing"
SIGNING = """    // locora: release signing (scripts/android-release-signing.py)
    val keystoreProperties = Properties().apply {
        System.getenv("LOCORA_ANDROID_KEYSTORE")?.let { path ->
            val keystore = file(path)
            if (keystore.isFile) keystore.inputStream().use { load(it) }
        }
    }
    signingConfigs {
        create("release") {
            keystoreProperties.getProperty("storeFile")?.let { storeFile = file(it) }
            storePassword = keystoreProperties.getProperty("storePassword")
            keyAlias = keystoreProperties.getProperty("keyAlias")
            keyPassword = keystoreProperties.getProperty("keyPassword")
        }
    }
"""
RELEASE = """        getByName("release") {
            if (keystoreProperties.getProperty("storeFile") != null) {
                signingConfig = signingConfigs.getByName("release")
            }
"""

path = sys.argv[1]
text = open(path).read()
if MARK not in text:
    if "android {\n" not in text or '        getByName("release") {\n' not in text:
        sys.exit("android-release-signing: unexpected build.gradle.kts layout")
    text = text.replace("android {\n", "android {\n" + SIGNING, 1)
    text = text.replace('        getByName("release") {\n', RELEASE, 1)
    open(path, "w").write(text)

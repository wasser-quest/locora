"""Lets the keyboard make room in the generated Android app (src-tauri/gen/android), once.

The activity draws edge to edge, and from Android 15 on the keyboard then covers the WebView
instead of shrinking it: fields and the app tour's panel at the bottom disappear behind it. The
content view gets the keyboard's height as bottom padding, so the page ends above the keyboard.
The project is generated by `cargo tauri android init` and not versioned, so the build script
applies this on every build.
"""
import sys

MARK = "// locora: keyboard insets"
IMPORTS = """import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
"""
INSETS = """    super.onCreate(savedInstanceState)
    // locora: keyboard insets (scripts/android-keyboard-insets.py)
    ViewCompat.setOnApplyWindowInsetsListener(findViewById(android.R.id.content)) { view, insets ->
      val keyboard = insets.getInsets(WindowInsetsCompat.Type.ime()).bottom
      view.setPadding(0, 0, 0, keyboard)
      insets
    }
"""

path = sys.argv[1]
text = open(path).read()
if MARK not in text:
    anchor = "    super.onCreate(savedInstanceState)\n"
    if "import androidx.activity.enableEdgeToEdge\n" not in text or anchor not in text:
        sys.exit("android-keyboard-insets: unexpected MainActivity.kt layout")
    text = text.replace(
        "import androidx.activity.enableEdgeToEdge\n",
        "import androidx.activity.enableEdgeToEdge\n" + IMPORTS,
        1,
    )
    text = text.replace(anchor, INSETS, 1)
    open(path, "w").write(text)
